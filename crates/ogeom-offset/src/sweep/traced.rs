//! What each profile edge and vertex of a sweep made, read off the swept
//! shape.
//!
//! A sweep's faces form strips, one per profile edge: each strip runs from
//! where the profile stands to where the sweep ends and may be cut across
//! into pieces (a mitre, a run boundary, a fitted segment, a boolean that
//! joined the pieces). Strips meet on rails, the paths of the profile's
//! vertices. The profile lies on the sweep where it starts, so each profile
//! edge's points lie on the wall that edge begins and each profile vertex
//! stands at the rail it begins. From there:
//!
//! - a rail is followed edge to edge: at a vertex where four edges meet it
//!   goes on along the one that shares no face with the edge it came by,
//!   and where more meet along the one such edge that is a crease;
//! - a strip is the faces reached from its first walls without crossing a
//!   rail or entering a cap. A face two strips reach at once goes to the
//!   one that meets it smoothly, if only one does (a run's end face flush
//!   with the next run's wall); otherwise it belongs to neither (a face in
//!   a mitre plane between two runs) and is traced to the profile as a
//!   whole.
//!
//! Where the caller knows the profile's placement further on (a pipe's
//! frames at the middle of each spine edge) the profile's points there
//! seed more first walls, so a run that meets the one before only through
//! a face across the sweep is still reached.
//!
//! The start cap is the face holding the profile's edges whose normal is
//! the profile's; the end cap a plane face through the sweep's end that
//! holds no rail.

use ogeom_algo::sweep::roles;
use ogeom_algo::{Built, Containment, classify_on_face, edge_vertices, placed_edge_curve};
use ogeom_core::{FastMap, OgeomResult, Tolerances};
use ogeom_geom::{Curve, Curve3d as _, Surface as _, TrimmedCurve};
use ogeom_math::{Plane, Point, Vector};
use ogeom_topo::{Model, SameKey, Shape, ShapeType, explore_unique};

/// The sine of the least angle two faces meet at across a crease: a
/// fitted strip's own pieces meet within their fit's turn, far below it.
const CREASE: f64 = 1e-3;

/// Where the sweep starts and ends, as the tracing needs them.
pub(crate) struct SweepEnds {
    /// The plane the profile stands in where the sweep starts, if it is
    /// planar.
    pub start: Option<Plane>,
    /// A point of the plane the end cap lies in, where the sweep has one.
    pub far: Option<Point>,
    /// Whether to record the caps and trace the faces no edge reaches to
    /// the profile: false for a loft's later sections, whose walls are
    /// the first section's.
    pub caps: bool,
    /// Rigid motions carrying the profile to where it stands further on,
    /// each of its edges there on its own wall: more first walls, for a
    /// sweep whose runs meet where no rail runs through (a run on past a
    /// corner fused to the next).
    pub carried: Vec<ogeom_math::Transform>,
}

/// `built` with each profile edge generating the walls it swept and the
/// cap edges it became, each profile vertex the rail edges it swept, the
/// caps recorded as the profile's start and end (their roles
/// [`roles::SWEEP_BOTTOM`] and [`roles::SWEEP_TOP`]), and every other face
/// generated by the profile. `reach` is how far off a face a point of the
/// profile may lie and still be on it: the walls' fitting tolerance.
///
/// `profile` is the profile as swept, standing where the sweep starts;
/// the records name `given`'s edges and vertices instead where the caller
/// moved a copy of its profile there (a copy keeps its edges' order).
///
/// # Errors
///
/// As the exploration and the geometry read off the shapes.
pub(crate) fn traced(
    model: &mut Model,
    mut built: Built,
    profile: &Shape,
    given: &Shape,
    ends: &SweepEnds,
    reach: f64,
    tol: Tolerances,
) -> OgeomResult<Built> {
    let reach = reach.max(tol.confusion() * 10.0);
    let graph = Graph::of(model, &built.shape, reach, tol)?;
    let n = graph.faces.len();

    // The profile, placed.
    let profile_edges = explore_unique(model, profile, ShapeType::Edge)?;
    let mut curves = Vec::with_capacity(profile_edges.len());
    for edge in &profile_edges {
        curves.push(placed_edge_curve(model, edge, tol)?);
    }
    let profile_vertices = explore_unique(model, profile, ShapeType::Vertex)?;
    let normal = ends.start.map(|p| p.normal().vector());
    let (named_edges, named_vertices) = {
        let edges = explore_unique(model, given, ShapeType::Edge)?;
        let vertices = explore_unique(model, given, ShapeType::Vertex)?;
        if edges.len() == profile_edges.len() && vertices.len() == profile_vertices.len() {
            (edges, vertices)
        } else {
            (profile_edges.clone(), profile_vertices.clone())
        }
    };

    // Each profile edge's first walls, and the start cap: the faces its
    // points lie on, told apart by whether they face as the profile does.
    let mut seeded: Vec<Vec<usize>> = vec![Vec::new(); n];
    let mut cap = vec![false; n];
    let mut bottom = vec![false; n];
    let placements: Vec<Option<ogeom_math::Transform>> = core::iter::once(None)
        .chain(ends.carried.iter().copied().map(Some))
        .collect();
    for (ei, placed) in curves.iter().enumerate() {
        let Some((curve, range)) = placed else {
            continue;
        };
        for share in [0.3, 0.5, 0.7] {
            let on_profile = curve.point_at(range.0 + (range.1 - range.0) * share, tol)?;
            for motion in &placements {
                let p = motion.map_or(on_profile, |m| m.apply(on_profile));
                let z = normal.map(|z| motion.map_or(z, |m| m.apply_vector(z)));
                for fi in 0..n {
                    let Some(face_normal) = graph.on_face(model, fi, p, tol)? else {
                        continue;
                    };
                    let facing = z.is_some_and(|z| {
                        face_normal.is_some_and(|m| m.dot(z).abs() > 1.0 - tol.angular())
                    });
                    if facing {
                        // Where the profile stands: the start cap. Further
                        // on, a face across the sweep is no wall.
                        if motion.is_none() {
                            bottom[fi] = true;
                            cap[fi] = true;
                        }
                    } else if !seeded[fi].contains(&ei) {
                        seeded[fi].push(ei);
                    }
                }
            }
        }
    }

    // The rails, from where each profile vertex stands.
    let mut rail = vec![false; graph.edges.len()];
    let mut rails_of: Vec<Vec<usize>> = vec![Vec::new(); profile_vertices.len()];
    for (vi, vertex) in profile_vertices.iter().enumerate() {
        let at = point_of(model, vertex)?;
        let mut starts: Vec<(usize, Option<usize>)> = Vec::new();
        if let Some(u) = graph.vertex_at(at, reach) {
            for &e in &graph.vertex_edges[u] {
                if !graph.lies_on_profile(model, e, ends.start, &curves, reach, tol)? {
                    starts.push((e, Some(u)));
                }
            }
        } else {
            // The vertex inside a result edge: a rail passing through it,
            // walked both ways.
            for e in 0..graph.edges.len() {
                if graph.passes(model, e, at, reach, tol)? {
                    starts.push((e, None));
                }
            }
        }
        for (e, from) in starts {
            match (from, graph.ends[e]) {
                (Some(u), _) => graph.walk(model, e, u, &mut rail, &mut rails_of[vi], tol)?,
                (None, Some((a, b))) => {
                    graph.walk(model, e, a, &mut rail, &mut rails_of[vi], tol)?;
                    graph.walk(model, e, b, &mut rail, &mut rails_of[vi], tol)?;
                }
                (None, None) => {
                    rail[e] = true;
                    push_once(&mut rails_of[vi], e);
                }
            }
        }
    }

    // The end cap: a plane face through the sweep's end holding no rail
    // and none of the profile's points.
    if let Some(far) = ends.far {
        for fi in 0..n {
            if cap[fi] || !seeded[fi].is_empty() {
                continue;
            }
            if graph.face_edges[fi].iter().any(|&e| rail[e]) {
                continue;
            }
            if let Some(plane) = ogeom_algo::find_plane(model, &graph.faces[fi], tol)?
                && plane.distance_to(far) <= reach
            {
                cap[fi] = true;
            }
        }
    }

    // The strips, grown a ring of faces at a time from the first walls.
    let mut owner: Vec<Owner> = (0..n)
        .map(|fi| match seeded[fi].as_slice() {
            _ if cap[fi] => Owner::Cap,
            [] => Owner::Free,
            [one] => Owner::Edge(*one),
            _ => Owner::Shared,
        })
        .collect();
    let mut frontier: Vec<usize> = (0..n)
        .filter(|&fi| matches!(owner[fi], Owner::Edge(_)))
        .collect();
    while !frontier.is_empty() {
        // Each claim on a face: the strip, and whether it comes across an
        // edge where the two faces meet smoothly.
        let mut claims: FastMap<usize, Vec<(usize, bool)>> = FastMap::default();
        for &fi in &frontier {
            let Owner::Edge(ei) = owner[fi] else {
                continue;
            };
            for &e in &graph.face_edges[fi] {
                if rail[e] {
                    continue;
                }
                for &g in &graph.edge_faces[e] {
                    if matches!(owner[g], Owner::Free) {
                        let smooth = !graph.meet_at_an_angle(
                            model,
                            fi,
                            g,
                            graph.middle(model, e, tol)?,
                            tol,
                        )?;
                        let claim = claims.entry(g).or_default();
                        if !claim.contains(&(ei, smooth)) {
                            claim.push((ei, smooth));
                        }
                    }
                }
            }
        }
        let mut next = Vec::new();
        let mut claimed: Vec<(usize, Vec<(usize, bool)>)> = claims.into_iter().collect();
        claimed.sort_unstable_by_key(|(g, _)| *g);
        for (g, by) in claimed {
            // One strip claiming it, or one claiming it smoothly where
            // several reach it: a run's end face flush with the next run's
            // wall is that wall's.
            let strips = |smooth_only: bool| -> Vec<usize> {
                let mut out: Vec<usize> = Vec::new();
                for &(ei, smooth) in &by {
                    if (smooth || !smooth_only) && !out.contains(&ei) {
                        out.push(ei);
                    }
                }
                out
            };
            let (all, smooth) = (strips(false), strips(true));
            let won = match (all.as_slice(), smooth.as_slice()) {
                ([one], _) | (_, [one]) => Some(*one),
                _ => None,
            };
            if let Some(ei) = won {
                owner[g] = Owner::Edge(ei);
                next.push(g);
            } else {
                owner[g] = Owner::Contested;
            }
        }
        frontier = next;
    }

    // The records.
    let mut traced_to_profile = Vec::new();
    for fi in 0..n {
        let face = graph.faces[fi].clone();
        let by: Vec<usize> = match owner[fi] {
            Owner::Edge(ei) => vec![ei],
            Owner::Shared => seeded[fi].clone(),
            Owner::Cap | Owner::Free | Owner::Contested => Vec::new(),
        };
        if let [one] = by.as_slice() {
            set_derived_fresh(model, &face, &named_edges[*one], roles::SWEEP_SIDE, profile)?;
        }
        for &ei in &by {
            built.history.generate(&named_edges[ei], face.clone());
            // The edges this wall shares with a cap are its edge's images
            // at the ends.
            for &e in &graph.face_edges[fi] {
                if !rail[e] && graph.edge_faces[e].iter().any(|&g| cap[g]) {
                    built
                        .history
                        .generate(&named_edges[ei], graph.edges[e].clone());
                }
            }
        }
        if !ends.caps {
            continue;
        }
        if cap[fi] {
            let role = if bottom[fi] {
                roles::SWEEP_BOTTOM
            } else {
                roles::SWEEP_TOP
            };
            set_derived_fresh(model, &face, given, role, profile)?;
            built.history.generate(given, face);
        } else if by.is_empty() {
            traced_to_profile.push(face);
        }
    }
    for face in traced_to_profile {
        built.history.generate(given, face);
    }
    for (vi, edges) in rails_of.iter().enumerate() {
        for &e in edges {
            let edge = graph.edges[e].clone();
            set_derived_fresh(
                model,
                &edge,
                &named_vertices[vi],
                roles::SWEEP_RAIL,
                profile,
            )?;
            built.history.generate(&named_vertices[vi], edge);
        }
    }
    built.history = built.history.without_repeated_images();
    Ok(built)
}

/// Which strip a face belongs to.
#[derive(Clone, Copy)]
enum Owner {
    /// Not reached yet.
    Free,
    /// A start or end cap.
    Cap,
    /// The strip of this profile edge.
    Edge(usize),
    /// A first wall of more than one profile edge: two collinear edges
    /// swept into one face.
    Shared,
    /// Reached by two strips at once.
    Contested,
}

/// The sweep's faces, edges and vertices and which meets which.
struct Graph {
    faces: Vec<Shape>,
    /// Each face's box, grown by the reach.
    boxes: Vec<ogeom_math::Aabb>,
    edges: Vec<Shape>,
    face_edges: Vec<Vec<usize>>,
    edge_faces: Vec<Vec<usize>>,
    ends: Vec<Option<(usize, usize)>>,
    points: Vec<Point>,
    vertex_edges: Vec<Vec<usize>>,
    /// How far off a face a point may lie and still be on it.
    reach: f64,
}

impl Graph {
    fn of(model: &Model, shape: &Shape, reach: f64, tol: Tolerances) -> OgeomResult<Self> {
        let faces = explore_unique(model, shape, ShapeType::Face)?;
        let mut boxes = Vec::with_capacity(faces.len());
        let mut edges = Vec::new();
        let mut edge_index: FastMap<SameKey, usize> = FastMap::default();
        let mut face_edges = Vec::with_capacity(faces.len());
        let mut edge_faces: Vec<Vec<usize>> = Vec::new();
        for (fi, face) in faces.iter().enumerate() {
            boxes.push(ogeom_algo::shape_bounds(model, face, tol)?.expanded(reach * 2.0));
            let mut own = Vec::new();
            for edge in explore_unique(model, face, ShapeType::Edge)? {
                let e = *edge_index.entry(SameKey(edge.clone())).or_insert_with(|| {
                    edges.push(edge);
                    edge_faces.push(Vec::new());
                    edges.len() - 1
                });
                push_once(&mut edge_faces[e], fi);
                push_once(&mut own, e);
            }
            face_edges.push(own);
        }
        let mut vertex_index: FastMap<SameKey, usize> = FastMap::default();
        let mut points = Vec::new();
        let mut vertex_edges: Vec<Vec<usize>> = Vec::new();
        let mut ends = Vec::with_capacity(edges.len());
        for (e, edge) in edges.iter().enumerate() {
            let Some((a, b)) = edge_vertices(model, edge)? else {
                ends.push(None);
                continue;
            };
            let mut index = |v: &Shape| -> OgeomResult<usize> {
                if let Some(&i) = vertex_index.get(&SameKey(v.clone())) {
                    return Ok(i);
                }
                points.push(point_of(model, v)?);
                vertex_edges.push(Vec::new());
                vertex_index.insert(SameKey(v.clone()), points.len() - 1);
                Ok(points.len() - 1)
            };
            let (a, b) = (index(&a)?, index(&b)?);
            push_once(&mut vertex_edges[a], e);
            push_once(&mut vertex_edges[b], e);
            ends.push(Some((a, b)));
        }
        Ok(Self {
            faces,
            boxes,
            edges,
            face_edges,
            edge_faces,
            ends,
            points,
            vertex_edges,
            reach,
        })
    }

    /// Whether `p` lies on face `fi` within the reach, and the face's
    /// normal at its foot there where it has one.
    #[allow(clippy::option_option)]
    fn on_face(
        &self,
        model: &Model,
        fi: usize,
        p: Point,
        tol: Tolerances,
    ) -> OgeomResult<Option<Option<Vector>>> {
        if !self.boxes[fi].contains(p) {
            return Ok(None);
        }
        let face = &self.faces[fi];
        let Some(data) = model.node(face).and_then(|n| n.data().as_face()) else {
            return Ok(None);
        };
        let Some(surface) = model.geometry().surface(data.surface) else {
            return Ok(None);
        };
        let reach = self.reach;
        let placement = face.transform(model.datums())?;
        let local = placement.inverse()?.apply(p);
        let foot = ogeom_algo::project_on_surface(surface, local, 16, tol)?;
        if foot.distance > reach {
            return Ok(None);
        }
        let at = placement.apply(foot.point);
        let deflection = ogeom_mesh::Deflection::for_tolerances(tol);
        if classify_on_face(model, face, at, deflection, tol)? == Containment::Out {
            return Ok(None);
        }
        let (u, v) = foot.parameters;
        let normal = surface
            .normal_at(u, v, tol)
            .ok()
            .map(|d| placement.apply_vector(d.vector()));
        Ok(Some(normal))
    }

    /// The vertex standing within `reach` of `at`.
    fn vertex_at(&self, at: Point, reach: f64) -> Option<usize> {
        self.points.iter().position(|p| p.distance(at) <= reach)
    }

    /// Whether edge `e` lies on the profile: in its plane, or on one of
    /// its edges where it has none.
    fn lies_on_profile(
        &self,
        model: &Model,
        e: usize,
        plane: Option<Plane>,
        curves: &[Option<(Curve, (f64, f64))>],
        reach: f64,
        tol: Tolerances,
    ) -> OgeomResult<bool> {
        let Some((curve, range)) = placed_edge_curve(model, &self.edges[e], tol)? else {
            return Ok(false);
        };
        let mid = curve.point_at(f64::midpoint(range.0, range.1), tol)?;
        if let Some(plane) = plane {
            return Ok(plane.distance_to(mid) <= reach);
        }
        for (profile_curve, profile_range) in curves.iter().flatten() {
            let trimmed = Curve::Trimmed(Box::new(TrimmedCurve::new(
                profile_curve.clone(),
                profile_range.0,
                profile_range.1,
                tol,
            )?));
            if ogeom_algo::project_on_curve(&trimmed, mid, 32, tol)?.distance <= reach {
                return Ok(true);
            }
        }
        Ok(false)
    }

    /// Whether edge `e` passes within `reach` of `at`.
    fn passes(
        &self,
        model: &Model,
        e: usize,
        at: Point,
        reach: f64,
        tol: Tolerances,
    ) -> OgeomResult<bool> {
        let Some((curve, range)) = placed_edge_curve(model, &self.edges[e], tol)? else {
            return Ok(false);
        };
        let trimmed = Curve::Trimmed(Box::new(TrimmedCurve::new(curve, range.0, range.1, tol)?));
        Ok(ogeom_algo::project_on_curve(&trimmed, at, 32, tol)?.distance <= reach)
    }

    /// Follow a rail from edge `e`, leaving vertex `from`, until it comes
    /// back on itself or reaches a vertex where it does not go on (a cap's
    /// corner). Where four edges meet it goes on along the one sharing no
    /// face with the edge it came by. Where more meet (inside a turned
    /// corner, where a strip's pieces meet the rail at one vertex) it goes
    /// on along the one such edge its two faces meet at an angle across,
    /// a strip's own pieces meeting smoothly or in one plane there.
    fn walk(
        &self,
        model: &Model,
        mut e: usize,
        mut from: usize,
        rail: &mut [bool],
        seen: &mut Vec<usize>,
        tol: Tolerances,
    ) -> OgeomResult<()> {
        loop {
            if seen.contains(&e) {
                return Ok(());
            }
            rail[e] = true;
            seen.push(e);
            let Some((a, b)) = self.ends[e] else {
                return Ok(());
            };
            if a == b {
                return Ok(());
            }
            let w = if a == from { b } else { a };
            let others: Vec<usize> = self.vertex_edges[w]
                .iter()
                .copied()
                .filter(|&o| o != e)
                .collect();
            if others.len() < 3 {
                return Ok(());
            }
            let across: Vec<usize> = others
                .into_iter()
                .filter(|&o| {
                    !self.edge_faces[o]
                        .iter()
                        .any(|f| self.edge_faces[e].contains(f))
                })
                .collect();
            let next = if across.len() == 1 && self.vertex_edges[w].len() == 4 {
                across[0]
            } else {
                let mut creased = Vec::new();
                for &o in &across {
                    if let [f, g] = self.edge_faces[o].as_slice()
                        && self.meet_at_an_angle(model, *f, *g, self.points[w], tol)?
                    {
                        creased.push(o);
                    }
                }
                let [one] = creased.as_slice() else {
                    return Ok(());
                };
                *one
            };
            e = next;
            from = w;
        }
    }

    /// The point halfway along edge `e`.
    fn middle(&self, model: &Model, e: usize, tol: Tolerances) -> OgeomResult<Point> {
        match placed_edge_curve(model, &self.edges[e], tol)? {
            Some((curve, range)) => curve.point_at(f64::midpoint(range.0, range.1), tol),
            None => Ok(self.ends[e].map_or(Point::ORIGIN, |(a, _)| self.points[a])),
        }
    }

    /// Whether faces `f` and `g` meet at an angle at `at`, a point of both.
    fn meet_at_an_angle(
        &self,
        model: &Model,
        f: usize,
        g: usize,
        at: Point,
        tol: Tolerances,
    ) -> OgeomResult<bool> {
        let normal = |fi: usize| -> OgeomResult<Option<Vector>> {
            let face = &self.faces[fi];
            let Some(data) = model.node(face).and_then(|n| n.data().as_face()) else {
                return Ok(None);
            };
            let Some(surface) = model.geometry().surface(data.surface) else {
                return Ok(None);
            };
            let placement = face.transform(model.datums())?;
            let foot =
                ogeom_algo::project_on_surface(surface, placement.inverse()?.apply(at), 16, tol)?;
            let (u, v) = foot.parameters;
            Ok(surface
                .normal_at(u, v, tol)
                .ok()
                .map(|d| placement.apply_vector(d.vector())))
        };
        let (Some(m), Some(n)) = (normal(f)?, normal(g)?) else {
            return Ok(false);
        };
        Ok(m.cross(n).magnitude() > CREASE)
    }
}

/// Record `shape` as derived from `from`, unless it is a node of the
/// profile itself, whose own provenance is not the sweep's to change.
fn set_derived_fresh(
    model: &mut Model,
    shape: &Shape,
    from: &Shape,
    role: ogeom_core::Role,
    profile: &Shape,
) -> OgeomResult<()> {
    let of_profile = explore_unique(model, profile, model.kind_of(shape)?)?
        .iter()
        .any(|s| s.is_partner(shape));
    if !of_profile {
        model.set_derived(shape, std::slice::from_ref(from), role)?;
    }
    Ok(())
}

/// The point a vertex stands at.
pub(crate) fn point_of(model: &Model, vertex: &Shape) -> OgeomResult<Point> {
    let Some(raw) = model
        .node(vertex)
        .and_then(|n| n.data().as_vertex().map(|d| d.point))
    else {
        ogeom_core::ogeom_bail!(Construction, "the vertex holds no point");
    };
    Ok(vertex.transform(model.datums())?.apply(raw))
}

fn push_once(list: &mut Vec<usize>, i: usize) {
    if !list.contains(&i) {
        list.push(i);
    }
}
