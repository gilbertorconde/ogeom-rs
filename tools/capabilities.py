#!/usr/bin/env python3
"""capabilities: the capability ledger, its rendered form, and its gate.

Two committed files carry the ledger:

- ``docs/capabilities.toml``: hand-written. One block per capability of the
  kernel, with a verdict and the evidence for it. The only file a person
  edits.
- ``docs/CAPABILITIES.md``: generated here, committed. The reviewable surface.

``generate`` renders CAPABILITIES.md from the ledger. ``check`` is the gate
`tools/check.sh` runs: it validates the ledger against the crate sources and
confirms the rendered file is current.

Verdicts, and what each must cite
=================================

- ``covered``: symbols (checked against rustdoc output) and tests.
- ``partial``: the same, plus ``restriction`` stating what is missing.
- ``absent``: ``plan`` naming the PLAN.md entry that owns it.
- ``divergent``: ``reasoning``, saying why we do this job another way on purpose.
- ``n/a``: ``reasoning``, saying why this is not a kernel capability for us.
- ``unreviewed``: nothing yet; counted against ``unreviewed_max``.
"""
from __future__ import annotations

import argparse
import collections
import hashlib
import os
import re
import sys
import tomllib

LEDGER = "docs/capabilities.toml"
RENDERED = "docs/CAPABILITIES.md"

VERDICTS = ("covered", "partial", "absent", "divergent", "n/a", "unreviewed")
EVIDENCE = {
    "covered": ("symbols", "tests"),
    "partial": ("symbols", "tests", "restriction"),
    "absent": ("plan",),
    "divergent": ("reasoning",),
    "n/a": ("reasoning",),
    "unreviewed": (),
}

def read_ledger(path: str) -> dict:
    with open(path, "rb") as fh:
        return tomllib.load(fh)


def ledger_checksum(path: str) -> str:
    return hashlib.sha256(open(path, "rb").read()).hexdigest()[:16]


# --------------------------------------------------------------------------
# generate
# --------------------------------------------------------------------------

def cmd_generate(args) -> int:
    ledger = read_ledger(args.ledger)
    caps = ledger.get("capability", [])
    by_verdict = collections.Counter(c["verdict"] for c in caps)

    lines = []
    w = lines.append
    w("# Capabilities")
    w("")
    w("**Generated by `tools/capabilities.py generate`; do not edit.** The input")
    w(f"is `{args.ledger}`, the only file a person edits. `docs/SCOPE.md`")
    w("defines what belongs in the kernel; this file records where it stands.")
    w("")
    w("One capability per thing a caller would ask for, not per type and not")
    w("per module. Each verdict cites the symbols and tests that back it, and")
    w("`tools/check.sh` fails if they drift apart.")
    w("")
    w("## Where the kernel stands")
    w("")
    w("| verdict | capabilities |")
    w("|---|---|")
    for v in VERDICTS:
        if by_verdict.get(v):
            w(f"| `{v}` | {by_verdict[v]} |")
    w("")
    w(f"{len(caps)} capabilities. "
      f"Ratchet: `unreviewed_max = {ledger['audit']['unreviewed_max']}`.")
    w("")

    by_crate = collections.defaultdict(list)
    for c in caps:
        by_crate[c.get("crate", "?")].append(c)
    w("## Capabilities")
    for crate in sorted(by_crate):
        w("")
        w(f"### {crate}")
        w("")
        for c in sorted(by_crate[crate], key=lambda c: c["id"]):
            w(f"- **{c['id']}**: {c['title']} · `{c['verdict']}`")
            if c["verdict"] == "partial":
                w(f"  - *restriction:* {c['restriction']}")
            if c["verdict"] in ("divergent", "n/a"):
                w(f"  - *reasoning:* {c['reasoning']}")
            if c["verdict"] == "absent":
                w(f"  - *owned by:* {c['plan']}")

    w("")
    w(f"<!-- ledger-checksum: {ledger_checksum(args.ledger)} -->")
    w("")

    with open(args.out, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {args.out}: {len(caps)} capabilities")
    return 0


# --------------------------------------------------------------------------
# check: the gate
# --------------------------------------------------------------------------

def workspace_crates() -> set[str]:
    """Doc-directory names of the crates currently in the workspace.

    `cargo doc` never removes output for crates that left, so `target/doc`
    accumulates ghosts, including everything moved to `outside/`. A citation
    resolving against a ghost would be exactly the quiet lie this gate exists
    to catch, so the walk is restricted to what `crates/` holds today.
    """
    out = set()
    for d in os.listdir("crates"):
        if os.path.isdir(os.path.join("crates", d)):
            out.add(d.replace("-", "_"))
    return out


def rustdoc_symbols(doc_root: str, crates: set[str]) -> set[str]:
    """Every documented item of the given crates, from rustdoc's file names.

    Rustdoc files an item under its *defining module* even when it is
    re-exported at the crate root (ogeom_algo::volume_properties lives at
    ogeom_algo/mass/fn.volume_properties.html), so the crate is the first
    path component and the module path in between is ignored. File names
    rather than HTML content: the set of items *is* the set of files.
    """
    syms = set()
    for crate in crates:
        root_dir = os.path.join(doc_root, crate)
        if not os.path.isdir(root_dir):
            continue
        for root, _dirs, files in os.walk(root_dir):
            for f in files:
                m = re.match(r"(?:struct|enum|trait|fn|constant|type|macro)\.(.+)\.html$", f)
                if m:
                    syms.add(f"{crate}::{m.group(1)}")
    return syms


def method_exists(doc_root: str, crate: str, type_name: str, method: str) -> bool:
    """A method cited as crate::Type::method must appear on the type's page."""
    import glob as _g
    for kind in ("struct", "enum", "trait"):
        for p in _g.glob(os.path.join(doc_root, crate, "**",
                                      f"{kind}.{type_name}.html"),
                         recursive=True):
            if re.search(rf'method\.{re.escape(method)}"',
                         open(p, errors="replace").read()):
                return True
    return False


def cmd_check(args) -> int:
    errors: list[str] = []
    ledger = read_ledger(args.ledger)
    caps = ledger.get("capability", [])

    # schema and evidence
    seen_ids = set()
    for c in caps:
        cid = c.get("id", "<missing id>")
        if cid in seen_ids:
            errors.append(f"duplicate capability id {cid}")
        seen_ids.add(cid)
        for field in ("id", "title", "crate", "verdict"):
            if field not in c:
                errors.append(f"{cid}: missing field '{field}'")
        v = c.get("verdict")
        if v not in VERDICTS:
            errors.append(f"{cid}: unknown verdict '{v}'")
            continue
        for field in EVIDENCE[v]:
            if not c.get(field):
                errors.append(f"{cid}: verdict '{v}' requires '{field}'")

    audit = ledger.get("audit", {})

    # ratchet
    n_unreviewed = sum(1 for c in caps if c.get("verdict") == "unreviewed")
    maxu = audit.get("unreviewed_max")
    if maxu is None:
        errors.append("audit.unreviewed_max missing")
    elif n_unreviewed > maxu:
        errors.append(f"{n_unreviewed} unreviewed capabilities exceeds "
                      f"unreviewed_max = {maxu}")

    # checksum: CAPABILITIES.md was generated from this ledger
    if os.path.exists(args.rendered):
        text = open(args.rendered).read()
        m = re.search(r"<!-- ledger-checksum: ([0-9a-f]+) -->", text)
        if not m:
            errors.append(f"{args.rendered} carries no ledger checksum")
        elif m.group(1) != ledger_checksum(args.ledger):
            errors.append(f"{args.rendered} is stale: regenerate with "
                          "`python3 tools/capabilities.py generate`")
    else:
        errors.append(f"{args.rendered} missing")

    # cited symbols resolve against rustdoc output, restricted to the crates
    # that are in the workspace today. target/doc accumulates ghosts of
    # crates that left, and resolving against one would be a quiet lie.
    doc = args.doc_root
    if os.path.isdir(doc):
        live = workspace_crates()
        syms = rustdoc_symbols(doc, live)
        for c in caps:
            for s in c.get("symbols", []):
                parts = s.split("::")
                if parts[0] not in live:
                    errors.append(f"{c['id']}: symbol {s} cites a crate that "
                                  "is not in the workspace")
                elif len(parts) == 2 and s not in syms:
                    errors.append(f"{c['id']}: symbol {s} not in {doc}")
                elif len(parts) == 3 and not method_exists(doc, *parts):
                    errors.append(f"{c['id']}: method {s} not in {doc}")
    else:
        errors.append(f"{doc} not built; run cargo doc first (check.sh does)")

    # cited tests resolve: file, or file::test_name
    for c in caps:
        for t in c.get("tests", []):
            path, _, name = t.partition("::")
            if not os.path.exists(path):
                errors.append(f"{c['id']}: test file {path} missing")
            elif name and name not in open(path, errors="replace").read():
                errors.append(f"{c['id']}: test {name} not in {path}")

    if errors:
        print("capabilities check FAILED:", file=sys.stderr)
        for e in errors:
            print(f"  {e}", file=sys.stderr)
        return 1
    print(f"capabilities check ok: {len(caps)} capabilities, "
          f"{n_unreviewed} unreviewed (max {maxu})")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ledger", default=LEDGER)
    ap.add_argument("--rendered", default=RENDERED)
    ap.add_argument("--doc-root", default="target/doc")
    sub = ap.add_subparsers(dest="command", required=True)
    sub.add_parser("generate", help="render docs/CAPABILITIES.md").set_defaults(func=cmd_generate)
    sub.add_parser("check", help="the gate check.sh runs").set_defaults(func=cmd_check)
    args = ap.parse_args()
    args.out = args.rendered
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
